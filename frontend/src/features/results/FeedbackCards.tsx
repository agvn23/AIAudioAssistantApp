import { useId } from 'react'
import type { Feedback } from './feedback'
import { describeArea, describeContext, describePriority } from './feedbackLabels'
import styles from './FeedbackCards.module.css'
import { formatNumber } from './format'

/**
 * The AI feedback as cards: the summary, one card per item with what the numbers
 * show, what to try and the measurements it cites, then caveats and how it was
 * generated. Evidence is shown as stored. Priority is written out, never only a colour.
 */

function formatGeneratedAt(iso: string): string {
  const date = new Date(iso)
  if (Number.isNaN(date.getTime())) return iso
  return date.toLocaleString(undefined, { dateStyle: 'medium', timeStyle: 'short' })
}

export function FeedbackCards({ feedback }: { feedback: Feedback }) {
  const caveatsId = useId()
  const hasReference = feedback.items.some((item) =>
    item.evidence.some((entry) => entry.metric.startsWith('reference.')),
  )

  return (
    <div>
      <p className={styles.summary}>{feedback.summary}</p>

      <ul className={styles.items}>
        {feedback.items.map((item, index) => (
          <li key={`${item.area}-${index}`} className={styles.item} data-priority={item.priority}>
            <div className={styles.itemHeader}>
              <h4 className={styles.itemTitle}>{describeArea(item.area)}</h4>
              <span className={styles.badge}>{describePriority(item.priority)}</span>
            </div>
            <dl className={styles.fields}>
              <div>
                <dt className={styles.term}>What the numbers show</dt>
                <dd className={styles.value}>{item.observation}</dd>
              </div>
              <div>
                <dt className={styles.term}>What to try</dt>
                <dd className={styles.value}>{item.suggestion}</dd>
              </div>
              <div>
                <dt className={styles.term}>Based on</dt>
                <dd className={styles.value}>
                  <ul className={styles.evidence}>
                    {item.evidence.map((entry) => (
                      <li key={entry.metric} className={styles.evidenceRow}>
                        <code>{entry.metric}</code>
                        <span className={styles.evidenceValue}>{formatNumber(entry.value)}</span>
                      </li>
                    ))}
                  </ul>
                </dd>
              </div>
            </dl>
          </li>
        ))}
      </ul>

      {hasReference ? (
        <p className={styles.note}>
          Evidence that starts with reference compares your track with the loudness target for the
          platform. A positive number means louder or higher than the target.
        </p>
      ) : null}

      {feedback.caveats.length > 0 ? (
        <section aria-labelledby={caveatsId} className={styles.caveats}>
          <h4 id={caveatsId} className={styles.itemTitle}>
            Caveats
          </h4>
          <ul className={styles.caveatList}>
            {feedback.caveats.map((caveat) => (
              <li key={caveat}>{caveat}</li>
            ))}
          </ul>
        </section>
      ) : null}

      {feedback.meta ? (
        <div className={styles.meta}>
          <p>
            Generated by {feedback.meta.model} on{' '}
            <time dateTime={feedback.meta.generated_at}>
              {formatGeneratedAt(feedback.meta.generated_at)}
            </time>
            .
          </p>
          <p>Context used: {describeContext(feedback.meta.context_used)}.</p>
        </div>
      ) : null}
    </div>
  )
}
