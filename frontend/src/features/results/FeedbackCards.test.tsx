import { render, screen, within } from '@testing-library/react'
import { describe, expect, it } from 'vitest'
import { expectNoA11yViolations } from '../../test/a11y'
import { sampleFeedback } from '../../test/fixtures/analysis'
import { parseFeedback, type Feedback } from './feedback'
import { FeedbackCards } from './FeedbackCards'

function sample(): Feedback {
  const parsed = parseFeedback(sampleFeedback)
  if (parsed === null) throw new Error('The sample feedback fixture must parse.')
  return parsed
}

/** The card of the item at that position (the item headings come first, in order). */
function itemOf(index: number): HTMLElement {
  const heading = screen.getAllByRole('heading', { level: 4 })[index]
  const item = heading?.closest('li') ?? null
  if (item === null) throw new Error(`No item at ${index}.`)
  return item
}

describe('FeedbackCards', () => {
  it('shows the summary', () => {
    render(<FeedbackCards feedback={sample()} />)

    expect(screen.getByText(/A balanced mix with a slightly strong low end/)).toBeInTheDocument()
  })

  it('has one heading per item, in order, then the caveats', () => {
    render(<FeedbackCards feedback={sample()} />)

    const names = screen.getAllByRole('heading', { level: 4 }).map((heading) => heading.textContent)
    expect(names).toEqual(['Loudness', 'Loudness', 'Spectrum', 'Caveats'])
  })

  it('writes the priority out in words', () => {
    render(<FeedbackCards feedback={sample()} />)

    expect(screen.getAllByText('Medium priority')).toHaveLength(2)
    expect(screen.getAllByText('Low priority')).toHaveLength(1)
  })

  it('shows what the numbers show and what to try', () => {
    render(<FeedbackCards feedback={sample()} />)

    const first = within(itemOf(0))
    expect(first.getByText(/1\.2 LU louder than the Spotify target/)).toBeInTheDocument()
    expect(first.getByText(/Spotify turns louder tracks down/)).toBeInTheDocument()
  })

  it('shows the cited measurements with their values as stored', () => {
    render(<FeedbackCards feedback={sample()} />)

    const first = within(itemOf(0))
    expect(first.getByText('loudness.integrated_lufs')).toBeInTheDocument()
    expect(first.getByText('-12.8')).toBeInTheDocument()
    expect(first.getByText('reference.integrated_lufs_difference')).toBeInTheDocument()
    expect(first.getByText('1.2')).toBeInTheDocument()
  })

  it('explains reference evidence once when it is cited', () => {
    render(<FeedbackCards feedback={sample()} />)

    expect(
      screen.getAllByText(/A positive number means louder or higher than the target/),
    ).toHaveLength(1)
  })

  it('has no reference note when no reference evidence is cited', () => {
    const feedback = sample()
    render(<FeedbackCards feedback={{ ...feedback, items: feedback.items.slice(2) }} />)

    expect(screen.queryByText(/A positive number means louder/)).not.toBeInTheDocument()
  })

  it('lists the caveats', () => {
    render(<FeedbackCards feedback={sample()} />)

    expect(
      screen.getByText('Tempo and key analysis used only the first 240 seconds of the audio file.'),
    ).toBeInTheDocument()
  })

  it('has no caveats section when there are none', () => {
    render(<FeedbackCards feedback={{ ...sample(), caveats: [] }} />)

    expect(screen.queryByRole('heading', { name: 'Caveats' })).not.toBeInTheDocument()
  })

  it('says which model wrote it, when, and for what context', () => {
    const { container } = render(<FeedbackCards feedback={sample()} />)

    expect(screen.getByText(/Generated by gemini-3\.5-flash/)).toBeInTheDocument()
    expect(container.querySelector('time')).toHaveAttribute(
      'datetime',
      '2026-11-10T12:00:00.000000Z',
    )
    expect(
      screen.getByText('Context used: genre house, platform spotify, stage Mix.'),
    ).toBeInTheDocument()
  })

  it('leaves out the generation details when there is no meta', () => {
    const { summary, items, caveats } = sample()

    const { container } = render(<FeedbackCards feedback={{ summary, items, caveats }} />)

    expect(screen.queryByText(/Generated by/)).not.toBeInTheDocument()
    expect(container.querySelector('time')).toBeNull()
  })

  it('shows an area and a priority it does not know', () => {
    const items = [
      {
        area: 'groove',
        priority: 'urgent',
        observation: 'Observation text.',
        suggestion: 'Suggestion text.',
        evidence: [{ metric: 'a.b', value: 1 }],
      },
    ]

    render(<FeedbackCards feedback={{ ...sample(), items }} />)

    expect(screen.getByRole('heading', { name: 'Groove' })).toBeInTheDocument()
    expect(screen.getByText('Urgent priority')).toBeInTheDocument()
  })

  it('has no accessibility violations', async () => {
    const { container } = render(<FeedbackCards feedback={sample()} />)

    await expectNoA11yViolations(container)
  })
})
